import { CLIP_GAP_MS, lineById, lineTexts, slotValues } from "./lines";
import type { Cue, QuizSpec, Scene, Timeline, VoiceLines } from "./types";

export class DurationError extends Error {}

export const HOOK_MIN = 2.6;
export const TIMER_SEC = 3.0;
export const TIMER_LAST_SEC = 3.6;
export const REVEAL_MIN = 1.3;
/** Shorts keep the pace of the top quiz channels: a short answer line needs no longer reveal. */
export const REVEAL_MIN_SHORT = 1.1;
export const DIFFUP_SEC = 0.8;
/** The level-up before question 4 also carries the "like if you got the first 3 right" banner, so it stays longer. */
export const LIKE_BANNER_AT = 3;
export const LIKE_BANNER_SEC = 1.7;
/** Shorts: the level-ups before questions 7 and 10 carry a subscribe banner and a "last question, save and comment" banner. */
export const SUB_BANNER_AT = 6;
export const LAST_BANNER_AT = 9;
export type CtaKind = "like" | "subscribe" | "last";
export const CTA_BANNER: Record<CtaKind, string> = {
  like: "LIKE if you got the first 3 right!",
  subscribe: "SUBSCRIBE for daily quizzes!",
  last: "LAST ONE! SAVE and COMMENT!",
};
/** Which call-to-action banner (and spoken line) goes with the level-up before question `index`, if any. */
export function ctaAt(spec: QuizSpec, index: number): CtaKind | undefined {
  if (index === LIKE_BANNER_AT) return "like";
  if (spec.profile === "long" || spec.noLikeVoice) return undefined;
  const kind = index === SUB_BANNER_AT ? "subscribe" : index === LAST_BANNER_AT ? "last" : undefined;
  return kind && spec.ctaLineIds?.[kind] ? kind : undefined;
}
/** Spoken with the "like" banner (clip generated by tools/tts). */
export const LIKE_VOICE = "Like if you got the first three right!";
export const OUTRO_MIN = 3.2;
export const OUTRO_MIN_SHORT = 2.8;
export const MAX_DURATION = 59;
/** Long videos: a longer answer window, a score screen before the outro, and up to 8.5 minutes. */
export const TIMER_SEC_LONG = 5.0;
export const TIMER_LAST_SEC_LONG = 6.0;
export const SCORE_SEC = 4.0;
export const MAX_DURATION_LONG = 510;
export const maxDuration = (profile?: "short" | "long"): number => (profile === "long" ? MAX_DURATION_LONG : MAX_DURATION);
const PAD = 0.12;

export function buildTimeline(spec: QuizSpec, deps: { clipMs: (text: string) => number; voice: VoiceLines }): Timeline {
  const { clipMs, voice } = deps;
  const long = spec.profile === "long";
  const scenes: Scene[] = [];
  const cues: Cue[] = [];
  let voiceFree = 0;

  const speakClips = (clips: string[], desired: number): { start: number; end: number } => {
    const sec = (clips.reduce((a, t) => a + clipMs(t), 0) + CLIP_GAP_MS * Math.max(0, clips.length - 1)) / 1000;
    const start = Math.max(desired, voiceFree + 0.05);
    voiceFree = start + sec;
    cues.push({ at: start, kind: "voice", clips });
    return { start, end: start + sec };
  };
  const speak = (lineId: string, desired: number, q?: (typeof spec.questions)[number]) =>
    speakClips(lineTexts(lineById(voice, lineId), slotValues(spec, q)), desired);

  let t = 0;
  const hook = speak(spec.hookLineId, 0.2);
  scenes.push({ kind: "hook", start: 0, end: Math.max(HOOK_MIN, hook.end + PAD) });
  t = scenes[0].end;

  for (const q of spec.questions) {
    const diffUp = spec.difficultyUpLineIds[q.index];
    if (diffUp !== undefined && q.index in spec.difficultyUpLineIds) {
      cues.push({ at: t, kind: "whoosh" });
      let dur = DIFFUP_SEC;
      const cta = ctaAt(spec, q.index);
      if (cta && !spec.noLikeVoice) { // the banner stays up while its call to action is spoken (instead of the level-up line)
        const id = spec.ctaLineIds?.[cta];
        const sp = id ? speak(id, t + 0.05) : speakClips([LIKE_VOICE], t + 0.05);
        dur = Math.max(LIKE_BANNER_SEC, sp.end + PAD - t);
      } else {
        speak(diffUp, t + 0.05);
        if (q.index === LIKE_BANNER_AT) dur = LIKE_BANNER_SEC;
      }
      scenes.push({ kind: "diffUp", start: t, end: t + dur, q: q.index });
      t += dur;
    }
    const last = q.index === spec.questions.length - 1;
    const timerSec = long ? (last ? TIMER_LAST_SEC_LONG : TIMER_SEC_LONG) : last ? TIMER_LAST_SEC : TIMER_SEC;
    scenes.push({ kind: "timer", start: t, end: t + timerSec, q: q.index });
    if (last) cues.push({ at: t, kind: "heartbeat" });
    for (let k = timerSec - 3; k < timerSec; k++) cues.push({ at: t + k, kind: "tick" });
    const startLine = q.askLineId ?? q.transitionLineId;
    if (startLine) speak(startLine, t + 0.1, q);
    if (q.countdownLineId) speak(q.countdownLineId, t + 1.2, q);
    t += timerSec;

    const rv = speak(q.revealLineId, t + 0.1, q);
    cues.push({ at: t, kind: "chime" });
    let end = Math.max(t + (long ? REVEAL_MIN : REVEAL_MIN_SHORT), rv.end + PAD);
    let factAt: number | undefined;
    if (q.fact) { // fun fact: read out right after the answer, shown on a "DID YOU KNOW?" panel
      const ft = speakClips([q.fact], rv.end + 0.2);
      factAt = ft.start - 0.05;
      end = Math.max(end, ft.end + 0.25);
    }
    scenes.push({ kind: "reveal", start: t, end, q: q.index, ...(factAt !== undefined ? { factAt } : {}) });
    t = end;
  }

  if (long) { // "How many did you get?" with the score tiers, before the outro line
    scenes.push({ kind: "score", start: t, end: t + SCORE_SEC });
    cues.push({ at: t, kind: "chime" });
    t += SCORE_SEC;
  }
  const outro = speak(spec.outroLineId, t + 0.2);
  const outroEnd = Math.max(t + (long ? OUTRO_MIN : OUTRO_MIN_SHORT), outro.end + 0.3);
  scenes.push({ kind: "outro", start: t, end: outroEnd });

  const duration = outroEnd;
  const max = maxDuration(spec.profile);
  if (duration > max) throw new DurationError(`timeline is ${duration.toFixed(1)}s, max ${max}s (seed ${spec.seed})`);
  cues.sort((a, b) => a.at - b.at);
  return { spec, duration, scenes, cues };
}
